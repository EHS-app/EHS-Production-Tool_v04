const fs = require("fs");

function addTranslations(filePath, translations) {
  let content = fs.readFileSync(filePath, "utf-8");
  // Find the end of the object
  const lastBraceIndex = content.lastIndexOf("}");
  if (lastBraceIndex === -1) {
    console.error("Could not find the end of the object in " + filePath);
    return;
  }
  
  let newEntries = "";
  for (const [key, value] of Object.entries(translations)) {
    if (!content.includes(`"${key}":`)) {
      newEntries += `  "${key}": ${JSON.stringify(value)},\n`;
    }
  }
  
  if (newEntries) {
    content = content.substring(0, lastBraceIndex) + ",\n" + newEntries + "};";
    // fix trailing comma if necessary, but adding a comma before newEntries is fine
    content = content.replace(/,(\s*),\n/, ",\n"); 
    fs.writeFileSync(filePath, content, "utf-8");
    console.log(`Added translations to ${filePath}`);
  } else {
    console.log(`No new translations to add to ${filePath}`);
  }
}

